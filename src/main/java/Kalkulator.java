    private void txtClear1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtClear1ActionPerformed
        // TODO add your handling code here:
        switch (pilih) {
            case 1:
                bil2=Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah=bil1+bil2;
                bil=Double.toString(jumlah);
                break;
            case 2:
                bil2=Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah=bil1-bil2;
                bil=Double.toString(jumlah);
                break;
            case 3:
                bil2=Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah=bil1*bil2;
                bil=Double.toString(jumlah);
                break;
            case 4:
                bil2=Double.parseDouble(String.valueOf(txtTampil.getText()));
                jumlah=bil1/bil2;
                bil=Double.toString(jumlah);
                break; 
        }        
        if (jumlah % 1 == 0) {
            txtTampil.setText(String.valueOf((int) jumlah));    
        }   else {
              txtTampil.setText(String.valueOf(jumlah));  
        }    
    }//GEN-LAST:event_txtClear1ActionPerformed

